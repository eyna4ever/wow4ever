PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, discord_id TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
 handle TEXT UNIQUE NOT NULL, avatar TEXT, role TEXT NOT NULL DEFAULT 'member'
 CHECK(role IN ('member','moderator','admin')), suspended INTEGER NOT NULL DEFAULT 0,
 public_history INTEGER NOT NULL DEFAULT 1, show_avatar INTEGER NOT NULL DEFAULT 1,
 notify INTEGER NOT NULL DEFAULT 1, created INTEGER NOT NULL, last_login INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, user_id INTEGER REFERENCES users ON DELETE CASCADE,
 csrf TEXT NOT NULL, created INTEGER NOT NULL, seen INTEGER NOT NULL, authenticated INTEGER
);
CREATE TABLE IF NOT EXISTS oauth (
 state TEXT PRIMARY KEY, session_token TEXT NOT NULL REFERENCES sessions ON DELETE CASCADE,
 verifier TEXT NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
 id INTEGER PRIMARY KEY, parent_id INTEGER REFERENCES categories ON DELETE RESTRICT,
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS topics (
 id INTEGER PRIMARY KEY, category_id INTEGER NOT NULL REFERENCES categories ON DELETE RESTRICT,
 author_id INTEGER REFERENCES users ON DELETE SET NULL, title TEXT NOT NULL,
 locked INTEGER NOT NULL DEFAULT 0, hidden INTEGER NOT NULL DEFAULT 0,
 created INTEGER NOT NULL, updated INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
 id INTEGER PRIMARY KEY, topic_id INTEGER NOT NULL REFERENCES topics ON DELETE CASCADE,
 author_id INTEGER REFERENCES users ON DELETE SET NULL, body TEXT NOT NULL,
 quote_id INTEGER REFERENCES posts ON DELETE SET NULL, hidden INTEGER NOT NULL DEFAULT 0,
 created INTEGER NOT NULL, edited INTEGER
);
CREATE TABLE IF NOT EXISTS follows (
 user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
 topic_id INTEGER NOT NULL REFERENCES topics ON DELETE CASCADE, PRIMARY KEY(user_id,topic_id)
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
 topic_id INTEGER NOT NULL REFERENCES topics ON DELETE CASCADE, PRIMARY KEY(user_id,topic_id)
);
CREATE TABLE IF NOT EXISTS reactions (
 user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
 post_id INTEGER NOT NULL REFERENCES posts ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN ('helpful','thanks')), PRIMARY KEY(user_id,post_id,kind)
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
 actor_id INTEGER REFERENCES users ON DELETE CASCADE,
 topic_id INTEGER NOT NULL REFERENCES topics ON DELETE CASCADE,
 post_id INTEGER NOT NULL REFERENCES posts ON DELETE CASCADE,
 kind TEXT NOT NULL, created INTEGER NOT NULL, seen INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS reports (
 id INTEGER PRIMARY KEY, reporter_id INTEGER REFERENCES users ON DELETE SET NULL,
 post_id INTEGER NOT NULL REFERENCES posts ON DELETE CASCADE, reason TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved')),
 created INTEGER NOT NULL, resolved INTEGER
);
CREATE UNIQUE INDEX IF NOT EXISTS report_open ON reports(reporter_id,post_id) WHERE status='open';
CREATE TABLE IF NOT EXISTS audit (
 id INTEGER PRIMARY KEY, actor_id INTEGER REFERENCES users ON DELETE SET NULL,
 action TEXT NOT NULL, target TEXT NOT NULL, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS topic_category ON topics(category_id,updated DESC);
CREATE INDEX IF NOT EXISTS posts_topic ON posts(topic_id,id);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id,created DESC);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS posts_author ON posts(author_id);
CREATE TABLE IF NOT EXISTS migrations(version INTEGER PRIMARY KEY, applied INTEGER NOT NULL);
