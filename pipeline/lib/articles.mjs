/**
 * Long-form article model shared by validation (documentary.mjs), the public
 * catalog boundary (public-catalog.mjs) and the static page generator (pages.mjs).
 * Pure functions only: no file system, no network.
 *
 * Every factual block carries `src`: a list of source keys that must resolve to
 * entry.sources[].key. A block without a resolvable source is invalid, so an
 * unsourced sentence can never reach a build.
 *
 * v16 (article.format 2, opt-in): one more block type, `analysis`, is the ONLY block allowed without
 * sources. It must carry the exact label ANALYSIS_LABEL, sit in a section of its own (no factual block
 * beside it) and is rendered as a distinct "Avis · IA" box. Format 1 articles are unchanged.
 */
export const ANALYSIS_LABEL = Object.freeze({fr: 'Analyse de la rédaction IA WoW4ever', en: 'WoW4ever AI editorial analysis'});
/** Section ids generated by the format 2 layout (cannot be reused by an authored section). */
export const FORMAT2_IDS = Object.freeze(['introduction', 'a-retenir', 'et-maintenant', 'sources', 'discussion']);
export const CATEGORY_SLUGS = Object.freeze({
  classes: {fr: 'classes', en: 'classes'},
  races: {fr: 'races', en: 'races'},
  zones: {fr: 'zones', en: 'zones'},
  instances: {fr: 'donjons-raids', en: 'dungeons-raids'},
  professions: {fr: 'metiers', en: 'professions'},
  items: {fr: 'objets', en: 'items'},
  quests: {fr: 'quetes', en: 'quests'},
  pvp: {fr: 'jcj', en: 'pvp'},
  creatures: {fr: 'creatures', en: 'creatures'},
  guides: {fr: 'guides', en: 'guides'},
  news: {fr: 'actualites', en: 'news'},
  glossary: {fr: 'glossaire', en: 'glossary'}
});
export const ILLUSTRATIONS = Object.freeze(Object.keys(CATEGORY_SLUGS));
const LANGS = ['fr', 'en'];
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+){0,12}$/;
const KEY = /^[a-z0-9][a-z0-9-]{1,60}$/;
const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const text = (value, max = 4000) => typeof value === 'string' && value.trim().length > 0 && value.length <= max;
const bilingual = (value, max) => isObject(value) && LANGS.every(lang => text(value[lang], max));

export function slugify(value) {
  return String(value ?? '').normalize('NFD').replace(/\p{M}/gu, '').toLowerCase()
    .replace(/[’'`]/g, '-').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').replace(/-{2,}/g, '-').slice(0, 80).replace(/-+$/, '');
}

/** Stable page slug: explicit for articles, derived from the reviewed titles for short entries. */
export function entrySlug(entry, lang) {
  const explicit = entry?.article?.slug?.[lang];
  return typeof explicit === 'string' && SLUG.test(explicit) ? explicit : slugify(entry?.title?.[lang]);
}
export function categoryPath(category, lang) { return `${lang}/${CATEGORY_SLUGS[category][lang]}/`; }
export function entryPath(entry, lang) { return `${categoryPath(entry.category, lang)}${entrySlug(entry, lang)}/`; }

/** Iterate over every sourced block of an article. */
export function* sourcedBlocks(article) {
  if (!isObject(article)) return;
  if (article.lead) yield {where: 'lead', block: article.lead};
  for (const [i, item] of (article.keyPoints ?? []).entries()) yield {where: `keyPoints[${i}]`, block: item};
  for (const [s, section] of (article.sections ?? []).entries()) {
    for (const [b, block] of (section?.blocks ?? []).entries()) {
      if (block?.type === 'analysis') continue; // v16: opinion, not a fact (see analysisBlocks)
      if (block?.type === 'list') for (const [i, item] of (block.items ?? []).entries()) yield {where: `sections[${s}].blocks[${b}].items[${i}]`, block: item};
      else yield {where: `sections[${s}].blocks[${b}]`, block};
    }
  }
  for (const [i, item] of (article.confirmed ?? []).entries()) yield {where: `confirmed[${i}]`, block: item};
  for (const [i, item] of (article.dates ?? []).entries()) yield {where: `dates[${i}]`, block: item};
  for (const [i, item] of (article.notes ?? []).entries()) yield {where: `notes[${i}]`, block: item};
}

/** v16: every analysis block (format 2 only). */
export function* analysisBlocks(article) {
  if (!isObject(article)) return;
  for (const [s, section] of (article.sections ?? []).entries()) {
    for (const [b, block] of (section?.blocks ?? []).entries()) if (block?.type === 'analysis') yield {where: `sections[${s}].blocks[${b}]`, block, section};
  }
}

export function validateArticle(entry) {
  const errors = [], article = entry.article;
  if (!isObject(article)) return ['article must be an object'];
  if (article.format !== 1 && article.format !== 2) errors.push('article.format must be 1 or 2');
  for (const lang of LANGS) if (!SLUG.test(article.slug?.[lang] ?? '')) errors.push(`article.slug.${lang} invalid`);
  if (!ILLUSTRATIONS.includes(article.illustration)) errors.push('article.illustration must name a category illustration');
  const keys = new Set((Array.isArray(entry.sources) ? entry.sources : []).map(source => source?.key).filter(Boolean));
  for (const source of entry.sources ?? []) {
    if (!KEY.test(source?.key ?? '')) errors.push('article sources require a key');
    if (!['fr', 'en'].includes(source?.language)) errors.push(`source ${source?.key}: language fr|en required`);
    // v17: an official reference page that shows no publication date (e.g. worldofwarcraft.blizzard.com/game/races/…) is declared
    // `undated: true` instead of inventing a date; news articles always carry theirs.
    const undated = source?.undated === true && source?.publishedAt === undefined && !/^https:\/\/news\.blizzard\.com\//.test(source?.url ?? '');
    if (!undated && !/^\d{4}-\d{2}-\d{2}$/.test(source?.publishedAt ?? '')) errors.push(`source ${source?.key}: publishedAt date required`);
  }
  if (!bilingual(article.lead, 1200)) errors.push('article.lead fr/en required');
  if (!Array.isArray(article.keyPoints) || article.keyPoints.length < 2) errors.push('at least two key points required');
  if (!Array.isArray(article.sections) || article.sections.length < 1) errors.push('at least one section required');
  const ids = new Set();
  for (const [s, section] of (article.sections ?? []).entries()) {
    if (!SLUG.test(section?.id ?? '') || ids.has(section.id)) errors.push(`sections[${s}].id invalid or duplicate`);
    ids.add(section?.id);
    if (!bilingual(section?.title, 200)) errors.push(`sections[${s}].title fr/en required`);
    if (!Array.isArray(section?.blocks) || !section.blocks.length) errors.push(`sections[${s}] requires blocks`);
    for (const [b, block] of (section?.blocks ?? []).entries()) {
      if (!['p', 'list', 'table', 'analysis'].includes(block?.type)) errors.push(`sections[${s}].blocks[${b}].type invalid`);
      if (block?.type === 'list' && (!Array.isArray(block.items) || !block.items.length)) errors.push(`sections[${s}].blocks[${b}] list requires items`);
      if (block?.type === 'table') {
        const width = block.head?.length;
        if (!Array.isArray(block.head) || !block.head.every(cell => bilingual(cell, 200))) errors.push(`sections[${s}].blocks[${b}] table head invalid`);
        if (!Array.isArray(block.rows) || !block.rows.length || !block.rows.every(row => Array.isArray(row) && row.length === width && row.every(cell => bilingual(cell, 400)))) errors.push(`sections[${s}].blocks[${b}] table rows invalid`);
        if (!bilingual(block.caption, 300)) errors.push(`sections[${s}].blocks[${b}] table caption required`);
      }
    }
  }
  if (article.format === 2) for (const [s, section] of (article.sections ?? []).entries()) if (FORMAT2_IDS.includes(section?.id)) errors.push(`sections[${s}].id is reserved by the article layout`);
  for (const {where, block, section} of analysisBlocks(article)) {
    if (article.format !== 2) { errors.push(`${where}: analysis blocks require article.format 2`); continue; }
    if (!isObject(block.label) || LANGS.some(lang => block.label[lang] !== ANALYSIS_LABEL[lang])) errors.push(`${where}: analysis block must be labelled exactly « ${ANALYSIS_LABEL.fr} » / « ${ANALYSIS_LABEL.en} »`);
    if (!bilingual(block, 2400)) errors.push(`${where}: fr/en text required`);
    if (section.blocks.some(other => other?.type !== 'analysis')) errors.push(`${where}: an analysis block must sit in a section without factual blocks`);
    if ('src' in block) {
      if (!Array.isArray(block.src)) errors.push(`${where}: src must be a list`);
      else for (const key of block.src) if (!keys.has(key) && ![...keys].some(k => k.startsWith(`${key}-`))) errors.push(`${where}: unknown source ${key}`);
    }
  }
  for (const {where, block} of sourcedBlocks(article)) {
    const isTable = block?.type === 'table';
    if (!isTable && !bilingual(block, 2400)) errors.push(`${where}: fr/en text required`);
    if (!Array.isArray(block?.src) || !block.src.length) { errors.push(`${where}: at least one source required`); continue; }
    for (const key of block.src) if (!keys.has(key) && ![...keys].some(k => k.startsWith(`${key}-`))) errors.push(`${where}: unknown source ${key}`);
  }
  for (const [i, item] of (article.dates ?? []).entries()) if (!/^\d{4}-\d{2}-\d{2}$/.test(item?.date ?? '')) errors.push(`dates[${i}].date invalid`);
  for (const [i, item] of (article.pending ?? []).entries()) if (!bilingual(item, 1200)) errors.push(`pending[${i}] fr/en required`);
  if (!Array.isArray(article.confirmed) || !article.confirmed.length) errors.push('confirmed list required');
  if (!Array.isArray(article.pending) || !article.pending.length) errors.push('pending list required (say explicitly what is not confirmed)');
  return errors;
}

/** Source groups: one citation number per publication, regardless of language versions. */
export function sourceGroups(entry) {
  const groups = new Map();
  for (const source of entry.sources ?? []) {
    const base = source.key ? source.key.replace(/-(fr|en)$/, '') : source.url;
    if (!groups.has(base)) groups.set(base, {key: base, versions: []});
    groups.get(base).versions.push(source);
  }
  return [...groups.values()].map((group, index) => ({...group, number: index + 1}));
}

export function articlePlainText(entry, lang) {
  const parts = [entry.title?.[lang], entry.description?.[lang]];
  const article = entry.article;
  if (isObject(article)) {
    for (const {block} of sourcedBlocks(article)) {
      if (block?.type === 'table') parts.push(block.caption?.[lang], ...(block.head ?? []).map(c => c[lang]), ...(block.rows ?? []).flat().map(c => c[lang]));
      else parts.push(block?.[lang], block?.label?.[lang]);
    }
    for (const {block} of analysisBlocks(article)) parts.push(block.label?.[lang], block[lang]);
    for (const section of article.sections ?? []) parts.push(section.title?.[lang]);
    for (const item of article.pending ?? []) parts.push(item[lang]);
  }
  return parts.filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
}

export function readingMinutes(entry, lang) {
  const words = articlePlainText(entry, lang).split(' ').filter(Boolean).length;
  return Math.max(1, Math.ceil(words / 200));
}
